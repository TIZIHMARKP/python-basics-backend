

# 3. Write a python program that creates two sets of numbers, finds their intersection and union, and prints the results.


set_a = {1, 2, 3}
set_b = {3, 4, 5}

print("Union: ", set_a.union(set_b))          # Output: {1, 2, 3, 4, 5}
print("Intersection: ", set_a.intersection(set_b))   # Output: {3}



